import { build } from '../../api/node_modules/esbuild/lib/main.js';
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

export async function chatClient() {
  const result = await build({ entryPoints: [fileURLToPath(new URL('./chat-entry.mjs', import.meta.url))],
    bundle: true, write: false, format: 'esm', platform: 'browser', target: 'es2022',
    minify: true, legalComments: 'none' });
  return '// Generated by telemetry/browser/build-chat.mjs. Do not edit.\n' + result.outputFiles[0].text;
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await writeFile(new URL('./chat-client.mjs', import.meta.url), await chatClient());
}

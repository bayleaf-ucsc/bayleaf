import { build } from '../../api/node_modules/esbuild/lib/main.js';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../../', import.meta.url));
export async function configuration() {
  const config = JSON.parse(await readFile(new URL('./config.json', import.meta.url), 'utf8'));
  if (Object.keys(config).length !== 1 || typeof config.landingEnabled !== 'boolean') {
    throw new Error('Expected only boolean landingEnabled in browser/config.json');
  }
  return config;
}
export async function artifacts(options) {
  const { landingEnabled } = options ?? await configuration();
  if (typeof landingEnabled !== 'boolean') throw new Error('Expected boolean landingEnabled');
  const result = await build({ absWorkingDir: root, stdin: {
    contents: "export { publicArrival } from './telemetry/browser/entry.mjs';",
    resolveDir: root }, bundle: true, write: false, format: 'iife', globalName: 'BayLeafArrival',
    platform: 'browser', target: 'es2022', minify: true, legalComments: 'none' });
  const code = result.outputFiles[0].text.trim();
  if (/<\/script/i.test(code)) throw new Error('Unsafe inline bundle');
  return {
    runtime: `// Generated by telemetry/browser/build.mjs. Do not edit.\nconst client = ${JSON.stringify(code)};\nexport function arrivalScript(destination: 'api' | 'sandbox' | 'proxies' | 'inboxes'): string {\n  return client + '\\nBayLeafArrival.publicArrival(' + JSON.stringify(destination) + ',true);';\n}\n`,
    landing: `// Generated by telemetry/browser/build.mjs; activation from telemetry/browser/config.json.\n${code}\nBayLeafArrival.publicArrival("landing",${landingEnabled});\n`,
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.length !== 2) throw new Error('Activation is configured in telemetry/browser/config.json, not CLI flags');
  const output = await artifacts();
  await writeFile(new URL('./runtime.ts', import.meta.url), output.runtime);
  await writeFile(new URL('../../landing/arrival.js', import.meta.url), output.landing);
}

import assert from 'node:assert/strict';
import { createTheme, THEME_KEY } from '../src/theme.js';
const root = new EventTarget(); root.dataset = {};
const media = new EventTarget(); media.matches = true;
const control = new EventTarget();
const values = new Map();
const storage = { getItem: (k) => values.get(k), setItem: (k, v) => values.set(k, v) };
const options = { root, media, control, storage };
const theme = createTheme(options);
assert.equal(root.dataset.theme, 'dark');
theme.set('light');
assert.equal(values.get(THEME_KEY), 'light');
media.dispatchEvent(new Event('change'));
assert.equal(root.dataset.theme, 'light');
const reloadedRoot = new EventTarget(); reloadedRoot.dataset = {};
assert.equal(createTheme({ ...options, root: reloadedRoot, media: Object.assign(new EventTarget(), { matches: true }) }).preference, 'light');
theme.set('system'); media.matches = false; media.dispatchEvent(new Event('change'));
assert.equal(root.dataset.theme, 'light');
media.matches = true; media.dispatchEvent(new Event('change'));
assert.equal(root.dataset.theme, 'dark');
theme.set('invalid'); assert.equal(theme.preference, 'system');
createTheme({ ...options, storage: { getItem() { throw Error(); }, setItem() { throw Error(); } } }).set('dark');
assert.equal(root.dataset.theme, 'dark');
console.log('theme preference, persistence, OS changes, invalid/blocked storage: pass');

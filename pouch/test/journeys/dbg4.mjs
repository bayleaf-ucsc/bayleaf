import { launch, instrument, sleep, rowMore, sheetClick, ensurePanel } from './lib.mjs';
const ctx = await launch({ fresh: true, userDataDir: '/tmp/pouch-qa/layout-dbg4' });
const page = ctx.pages()[0] ?? await ctx.newPage();
await page.setViewportSize({ width: 1280, height: 800 });
instrument(page);
await page.goto('http://127.0.0.1:8744/pouch.html'); await page.waitForSelector('#tree .row');
page.dialogQueue.push('assignment/src/lib'); await rowMore(page, '/work'); await sheetClick(page, 'New folder here'); await sleep(400);
page.dialogQueue.push('readme.md'); await rowMore(page, '/work/assignment'); await sheetClick(page, 'New file here'); await sleep(600);
console.log('panel', await page.getAttribute('#app', 'data-panel'));
await page.click('#close-file').catch(() => {});
await ensurePanel(page, 'files');
await page.focus('#files .panel-close'); await page.keyboard.press('Tab');
const at = () => page.evaluate(() => ({ tag: document.activeElement?.tagName, id: document.activeElement?.id, cls: document.activeElement?.className, path: document.activeElement?.dataset?.path }));
console.log('tab', await at());
await page.keyboard.press('Home'); console.log('home', await at());
await page.keyboard.press('ArrowDown'); console.log('down', await at());
for (let i = 0; i < 3; i++) await page.keyboard.press('ArrowDown');
console.log('at', await at());
await page.keyboard.press('Enter'); await sleep(600);
console.log('panel', await page.getAttribute('#app', 'data-panel'), 'focusable stops', await page.$$eval('#tree .row[tabindex="0"]', (r) => r.map((x) => x.dataset.path)));
await ensurePanel(page, 'files');
console.log('stops after', await page.$$eval('#tree .row[tabindex="0"]', (r) => r.map((x) => x.dataset.path)));
await page.focus('#files .panel-close'); await page.keyboard.press('Tab');
console.log('tab2', (await at()).path);
await page.evaluate(() => { window.__r = document.activeElement; document.addEventListener('focusout', (e) => console.log('focusout', e.target.className || e.target.tagName, '->', e.relatedTarget?.className || e.relatedTarget?.tagName), true); const t = document.querySelector('#tree'); const orig = t.replaceChildren.bind(t); t.replaceChildren = (...a) => { console.log('tree rebuilt', new Error().stack.split('\n').slice(2, 7).join(' < ')); return orig(...a); }; });
page.on('console', (m) => console.log('PAGE', m.text()));
await page.keyboard.press('Shift+F10'); await sleep(300);
console.log('sheet open', !!(await page.$('#sheet[open]')), 'panel', await page.getAttribute('#app', 'data-panel'), 'sheet title', await page.textContent('#sheet-title'), 'focused', await page.evaluate(() => document.activeElement.textContent));
await page.keyboard.press('Escape'); await sleep(200);
console.log('r connected', await page.evaluate(() => window.__r.isConnected), 'after esc', await at(), await page.evaluate(() => document.activeElement?.outerHTML.slice(0, 120)));
await ctx.close();

import { launch, instrument, sleep, URL } from './lib.mjs';
const ctx = await launch({ fresh: true, userDataDir: '/tmp/pouch-qa/layout-smoke' });
const page = ctx.pages()[0] ?? await ctx.newPage();
await page.setViewportSize({ width: 1280, height: 800 });
const errors = instrument(page);
await page.goto(URL);
await page.waitForSelector('#badge.ok', { timeout: 60_000 }).catch(() => {});
await sleep(1500);
await page.screenshot({ path: '/tmp/pouch-qa/shots/layout-smoke-desktop.png' });
await page.click('#flipper'); await sleep(300);
await page.click('#rail [data-panel=usage]'); await sleep(800);
await page.screenshot({ path: '/tmp/pouch-qa/shots/layout-smoke-desktop2.png' });
console.log('errors', errors);
await ctx.close();
const m = await launch({ mobile: true, fresh: true, userDataDir: '/tmp/pouch-qa/layout-smoke-m' });
const mp = m.pages()[0] ?? await m.newPage();
const me = instrument(mp);
await mp.goto(URL); await sleep(3000);
await mp.screenshot({ path: '/tmp/pouch-qa/shots/layout-smoke-mobile.png' });
await mp.click('#flipper'); await sleep(400);
await mp.screenshot({ path: '/tmp/pouch-qa/shots/layout-smoke-mobile-drawer.png' });
console.log('m errors', me);
await m.close();

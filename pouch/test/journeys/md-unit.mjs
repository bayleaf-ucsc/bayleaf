import { fileURLToPath } from 'node:url';
// Unit tests for pouch/src/markdown.js with a fake DOM (linkedom).
import { parseHTML } from 'linkedom';
const { document, window } = parseHTML('<!doctype html><html><body></body></html>');
globalThis.document = document; globalThis.window = window;
for (const k of ['navigator', 'MutationObserver', 'requestAnimationFrame']) globalThis[k] ??= window[k] ?? (() => {});
const P = fileURLToPath(new URL('../../src/', import.meta.url));
const { renderMarkdown, parseTarget } = await import(P + 'markdown.js');
let highlight = null;
try { ({ highlight } = await import(P + 'editor.js')); } catch (e) { console.log('editor.js not importable in Node:', e.message.split('\n')[0]); }
const files = new Set(['/work/a.js', '/work/app.js', '/work/b.py']), dirs = new Set(['/work', '/work/src']);
const opened = [], ext = [];
const ctx = { doc: document, cwd: '/work', kind: (p) => files.has(p) ? 'file' : dirs.has(p) ? 'dir' : 'missing',
  open: (t) => opened.push(t), external: (u) => ext.push(u), highlight: highlight && ((c, l) => highlight(c, l, document)), copy: async () => {} };
const R = (md) => { const d = document.createElement('div'); d.append(...renderMarkdown(md, ctx)); return d; };
let fail = 0;
const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) fail++; };
const noActive = (d) => !d.querySelector('script,img,iframe,a,[onerror],[onclick],[href],[src],object,embed,style');

let d = R('hi <img src=x onerror=alert(1)> and\n\n<script>alert(1)</script>\n\n<div onclick="x">b</div>');
ok(noActive(d) && d.textContent.includes('<img src=x onerror=alert(1)>') && d.textContent.includes('<script>alert(1)</script>'), 'raw HTML is visible text, no elements');
d = R('[x](javascript:alert(1)) [d](data:text/html,<b>) [m](mailto:a@b.c) [f](file:///etc/passwd)');
ok(noActive(d) && !d.querySelector('button') && d.textContent.includes('(javascript:alert(1))'), 'non-http schemes are plain text');
d = R('![a](https://evil.example/x.png)');
const ib = d.querySelector('button.ext');
ok(noActive(d) && ib && ib.textContent.includes('image: a') && ib.textContent.includes('evil.example'), 'image renders as external link, no <img>');
ib.click(); ok(ext[0] === 'https://evil.example/x.png', 'external click goes through ctx.external');
d = R('see https://developer.mozilla.org/en-US/ and [docs](https://developer.mozilla.org/x?q=secret) and www.example.com');
const eb = [...d.querySelectorAll('button.ext')];
ok(eb.length === 3 && eb[1].textContent === 'docs (developer.mozilla.org)' && !eb[0].querySelector('.host'), 'autolinks and host suffix');
d = R('[a.js:12](/work/a.js:12) [x](pouch:///work/a.js#L5-L9) [y](pouch:/work/b.py:3:4) [rel](app.js#L7) [dir](/work/src) [gone](/work/nope.js)');
const fb = [...d.querySelectorAll('button.path')];
fb.forEach((b) => b.click());
ok(JSON.stringify(opened.map((t) => [t.path, t.line ?? null, t.kind])) === JSON.stringify([['/work/a.js', 12, 'file'], ['/work/a.js', 5, 'file'], ['/work/b.py', 3, 'file'], ['/work/app.js', 7, 'file'], ['/work/src', null, 'dir']]), 'file links resolve with line suffixes, folder kind');
ok(d.querySelector('span.path.missing')?.title.includes('/work/nope.js'), 'missing path muted with title');
opened.length = 0;
d = R('Edit `/work/a.js:3` and `app.js`, not `foo`.');
ok(d.querySelectorAll('button.path > code').length === 2, 'inline code that is an existing path becomes a link');
d = R('Partial:\n\n```js\nconst x = 1;\nfunction f(');
ok(d.querySelector('.code pre code') && d.querySelector('.code-head').textContent.startsWith('js'), 'unclosed fence renders as a code block');
if (highlight) ok(d.querySelector('code .tok-keyword')?.textContent === 'const', 'js code tokens carry tok- classes');
d = R('```python\ndef f():\n  return "s"  # c\n```');
if (highlight) ok(d.querySelector('.tok-keyword') && d.querySelector('.tok-string') && d.querySelector('.tok-comment'), 'python highlighting');
d = R('```html\n<script>alert(1)</script>\n```');
ok(noActive(d) && d.querySelector('pre').textContent === '<script>alert(1)</script>', 'html code block stays text');
d = R('a *unclosed and **bold');
ok(!d.querySelector('em,strong') && d.textContent === 'a *unclosed and **bold', 'unclosed emphasis is text');
d = R('| a | b |\n|:-|-:|\n| 1 | `x` |\n| ~~s~~ | 2 |');
ok(d.querySelector('div.table > table thead th') && d.querySelectorAll('tbody tr').length === 2 && d.querySelector('del'), 'GFM table + strikethrough');
d = R('- [x] done\n- [ ] todo\n\n1. one\n2. two');
const boxes = d.querySelectorAll('li.task input[type=checkbox]');
ok(boxes.length === 2 && boxes[0].checked && !boxes[1].checked && boxes[0].disabled, 'task list checkboxes, disabled');
ok(d.querySelector('ol li') && d.querySelector('ul.tight'), 'ordered list, tight list class');
d = R('# H1\n\n> quote\n\n---\n\nline one  \nline two');
ok(d.querySelector('h1') && d.querySelector('blockquote') && d.querySelector('hr') && d.querySelector('br'), 'heading, quote, hr, hard break');
d = R('[ref][1]\n\n[1]: javascript:alert(1)');
ok(!d.querySelector('button') && noActive(d), 'reference link to javascript: is text');
ok(parseTarget('pouch:///work/a.js').path === '/work/a.js' && parseTarget('../../etc/x').path === '/etc/x' && parseTarget('#top') === null, 'parseTarget edge cases');
d = R('Look at /work/a.js:4 now');
ok(true, 'text hook absent is fine');
console.log(fail ? `${fail} FAILED` : 'ALL PASS');
process.exit(fail ? 1 : 0);
